"""SQLite access: connections, schemas, migrations.

Concurrency model (PLAN 2 section 11). Several server processes run at once -
one per editor window, one per terminal session - all against the same store.
So: WAL, a generous busy timeout, retry-with-backoff on write, and short write
transactions. Bulk work happens under the indexer lease (see lease.py), not in
a long-held transaction.

Durable vs rebuildable (PLAN 2 section 3): everything in repo.db is durable.
That includes `files` and `symbols`, which may look derivable from source but
are not - a tombstone for a deleted symbol (PLAN.md section 4) cannot be
regenerated by parsing code that no longer contains it. Only the FTS index and
parse artifacts are genuinely rebuildable.

Deletion policy (PLAN.md section 10): no ON DELETE CASCADE anywhere in the
durable graph. Losing a symbol row must never take its warnings, decisions and
bug history with it. Durable entities are tombstoned, never deleted.
"""

from __future__ import annotations

import json
import sqlite3
import time
from pathlib import Path
from typing import Any, Iterable

SCHEMA_VERSION = 8

# Columns added after a schema version shipped. Migration is first-class
# (PLAN.md section 11): additive, idempotent, and never destructive.
ADDED_COLUMNS: list[tuple[str, str, str]] = [
    ("symbols", "calls_raw", "TEXT"),
    ("symbols", "token_signature", "TEXT"),
    # Usage signal. A memory that agents keep opening has proven itself in a
    # way no authored severity can; one nobody has ever opened has not.
    ("memories", "access_count", "INTEGER DEFAULT 0"),
    ("memories", "last_accessed_at", "TEXT"),
    ("memories", "surfaced_count", "INTEGER DEFAULT 0"),
    # Import resolution is a second pass, like call resolution, so the raw
    # specs have to survive on the file row between the two.
    ("files", "imports_raw", "TEXT"),
    # Decorators are what make an entry point recognisable.
    ("symbols", "decorators", "TEXT"),
    # Which extractor version last wrote this file's rows. NULL means "before
    # this column existed", which is older than any real version.
    ("files", "extract_version", "INTEGER"),
    # Which extractor version computed this anchor's fingerprints. Lets a
    # change to the fingerprint ALGORITHM be told apart from a change to the
    # code, so improving the extractor does not cost the store its trust.
    ("anchors", "extract_version", "INTEGER"),
    # Receiver name -> possible types, the evidence the receiver_typed call
    # tier resolves through.
    ("symbols", "receiver_types", "TEXT"),
]

BUSY_TIMEOUT_MS = 15000
WRITE_RETRIES = 8


