def connect(path: Path, *, readonly: bool = False) -> sqlite3.Connection:
    """Open a store with the pragmas the concurrency model depends on."""
    path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(path), timeout=BUSY_TIMEOUT_MS / 1000.0, isolation_level=None)
    conn.row_factory = sqlite3.Row
    conn.execute(f"PRAGMA busy_timeout = {BUSY_TIMEOUT_MS}")
    conn.execute("PRAGMA journal_mode = WAL")
    conn.execute("PRAGMA synchronous = NORMAL")
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def init_catalog(path: Path) -> sqlite3.Connection:
    conn = connect(path)
    _apply_schema(conn, CATALOG_SCHEMA)
    return conn


def init_repo_store(path: Path) -> sqlite3.Connection:
    conn = connect(path)
    _apply_schema(conn, REPO_SCHEMA)
    return conn


def _apply_schema(conn: sqlite3.Connection, schema: str) -> None:
    """Create tables, retrying if another process is mid-create.

    executescript() commits any pending transaction before it runs, so it must
    not be wrapped in write_tx. Concurrent first-open from several processes is
    normal here - every statement is IF NOT EXISTS, so the loser just retries.
    """
    delay = 0.05
    for attempt in range(WRITE_RETRIES):
        try:
            conn.executescript(schema)
            _migrate(conn)
            _backfill_fts(conn)
            _repair_ref_commits(conn)
            _backfill_test_coverage(conn)
            _set_version(conn)
            return
        except sqlite3.OperationalError as exc:
            if ("locked" not in str(exc) and "busy" not in str(exc)) or attempt == WRITE_RETRIES - 1:
                raise
            time.sleep(delay)
            delay *= 2



def _backfill_fts(conn: sqlite3.Connection) -> None:
    """Index any memory that predates the search index.

    A derived index added after the fact is empty for everything already
    stored, and a half-populated FTS table fails silently: search simply
    returns fewer results, with nothing to indicate why. Measured on a real
    store, 25 of 34 memories were invisible to text search.

    Cheap and idempotent - it inserts only what is missing, so it costs one
    indexed anti-join on every open after the first.
    """
    try:
        missing = conn.execute(
            "SELECT m.memory_id, m.title, m.body, m.kind FROM memories m"
            " LEFT JOIN fts_memories f ON f.memory_id = m.memory_id"
            " WHERE f.memory_id IS NULL LIMIT 5000"
        ).fetchall()
    except sqlite3.OperationalError:
        return          # table not created yet on this connection
    if not missing:
        return
    try:
        conn.execute("BEGIN IMMEDIATE")
        conn.executemany(
            "INSERT INTO fts_memories (memory_id, title, body, kind) VALUES (?,?,?,?)",
            [(r[0], r[1] or "", (r[2] or "")[:4000], r[3] or "") for r in missing],
        )
        conn.execute("COMMIT")
    except sqlite3.OperationalError:
        try:
            conn.execute("ROLLBACK")
        except sqlite3.Error:
            pass


# Ref names are not commit ids. A store that recorded one has a permanently
# broken equality test: `unreviewed_caller` compares a symbol's last_seen_commit
# against an anchor's last_verified_commit, so "HEAD" on one side and a real SHA
# on the other reports every governed symbol as unreviewed, forever.
_REF_NAMES = ("HEAD", "head", "@", "ORIG_HEAD", "FETCH_HEAD", "MERGE_HEAD")

_REF_COLUMNS = (
    ("memories", ("created_commit", "last_verified_commit")),
    ("anchors", ("commit_observed", "last_verified_commit")),
    ("symbols", ("last_seen_commit", "deleted_at_commit")),
    ("files", ("first_seen_commit", "last_seen_commit", "deleted_at_commit")),
    ("code_edges", ("valid_from_commit", "valid_until_commit")),
)



# Rule kinds a test can guard. Mirrors compiler._link_test_coverage; kept here
# so the backfill does not import the compiler at schema time.
_GUARDABLE = ("invariant", "warning", "contract", "security", "decision")


def _backfill_test_coverage(conn: sqlite3.Connection) -> None:
    """Create GUARDED_BY edges for events recorded before that linking existed.

    Same failure mode as the FTS backfill: a feature added later leaves every
    earlier row permanently wrong, and the symptom is silent. Here the
    untested-invariant diagnostic kept reporting rules whose test was recorded
    in the very same call - which trains people to ignore the finding.

    Reconstructed from source_event, so it only ever links a rule to a test the
    author actually recorded alongside it. Idempotent.
    """
    try:
        pairs = conn.execute("""
            SELECT r.memory_id AS rule_id, t.memory_id AS test_id
            FROM memories r
            JOIN memories t ON t.source_event = r.source_event
            WHERE r.kind IN (?,?,?,?,?) AND t.kind = 'test_evidence'
              AND r.status='ACTIVE' AND t.status='ACTIVE'
              AND r.source_event IS NOT NULL
              -- Imports share one synthetic event id, so joining on it would
              -- claim every imported test covers every imported rule. Measured
              -- on a 48-memory import: 264 false coverage claims, which is
              -- worse than none because it silences the untested-rule check.
              AND r.source_event NOT LIKE 'import:%' 
              AND NOT EXISTS (
                  SELECT 1 FROM memory_edges e
                  WHERE e.from_id = r.memory_id AND e.to_id = t.memory_id
                    AND e.kind = 'GUARDED_BY')
            LIMIT 2000
        """, _GUARDABLE).fetchall()
    except sqlite3.OperationalError:
        return
    if not pairs:
        return

    from datetime import datetime, timezone
    stamp = datetime.now(timezone.utc).isoformat(timespec="milliseconds")
    try:
        conn.execute("BEGIN IMMEDIATE")
        conn.executemany(
            "INSERT OR IGNORE INTO memory_edges (edge_id, from_id, to_id, kind, edge_class,"
            " status, confidence, source, created_at)"
            " VALUES (?,?,?,'GUARDED_BY','asserted','ACTIVE',0.9,'backfill',?)",
            [("edge_bf" + rule[-8:] + test[-8:], rule, test, stamp) for rule, test in pairs],
        )
        conn.execute("COMMIT")
    except sqlite3.OperationalError:
        try:
            conn.execute("ROLLBACK")
        except sqlite3.Error:
            pass

def _repair_ref_commits(conn: sqlite3.Connection) -> None:
    """Null out ref names stored where a commit id belongs.

    NULL is honest - "we do not know which commit" is a state the graph already
    handles, whereas a ref name is a value that compares wrongly forever. Runs
    once per store in practice: after the first pass there is nothing to match.
    """
    placeholders = ",".join("?" for _ in _REF_NAMES)
    try:
        conn.execute("BEGIN IMMEDIATE")
        for table, columns in _REF_COLUMNS:
            for column in columns:
                try:
                    conn.execute(
                        f"UPDATE {table} SET {column} = NULL"
                        f" WHERE {column} IN ({placeholders})", _REF_NAMES)
                except sqlite3.OperationalError:
                    continue        # table or column absent in this schema
        conn.execute("COMMIT")
    except sqlite3.OperationalError:
        try:
            conn.execute("ROLLBACK")
        except sqlite3.Error:
            pass

def _migrate(conn: sqlite3.Connection) -> None:
    """Apply additive column migrations to a store created by an older version.

    Only columns are added, never dropped or retyped. A durable knowledge graph
    must not lose data to a schema bump.
    """
    for table, column, decl in ADDED_COLUMNS:
        exists = one(conn.execute("SELECT name FROM sqlite_master WHERE type='table' AND name=?", (table,)))
        if not exists:
            continue
        columns = {r["name"] for r in conn.execute(f"PRAGMA table_info({table})")}
        if column not in columns:
            conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {decl}")


def _set_version(conn: sqlite3.Connection) -> None:
    current = conn.execute("PRAGMA user_version").fetchone()[0]
    if current != SCHEMA_VERSION:
        conn.execute(f"PRAGMA user_version = {SCHEMA_VERSION}")


class write_tx:
    """Short write transaction with retry.

    Another process may hold the write lock. `BEGIN IMMEDIATE` takes it up
    front so we fail fast and retry rather than discovering the conflict at
    COMMIT after doing all the work.
    """

    def __init__(self, conn: sqlite3.Connection, retries: int = WRITE_RETRIES):
        self.conn = conn
        self.retries = retries

    def __enter__(self) -> sqlite3.Connection:
        delay = 0.05
        for attempt in range(self.retries):
            try:
                self.conn.execute("BEGIN IMMEDIATE")
                return self.conn
            except sqlite3.OperationalError as exc:
                if "locked" not in str(exc) and "busy" not in str(exc):
                    raise
                if attempt == self.retries - 1:
                    raise
                time.sleep(delay)
                delay *= 2
        raise sqlite3.OperationalError("could not acquire write lock")

    def __exit__(self, exc_type, exc, tb) -> bool:
        if exc_type is None:
            self.conn.execute("COMMIT")
        else:
            try:
                self.conn.execute("ROLLBACK")
            except sqlite3.Error:
                pass
        return False


def rows(cur: Iterable[sqlite3.Row]) -> list[dict[str, Any]]:
    """sqlite3.Row -> plain dicts, so results are JSON-serialisable."""
    return [dict(r) for r in cur]


def one(cur: Iterable[sqlite3.Row]) -> dict[str, Any] | None:
    for r in cur:
        return dict(r)
    return None


def jdump(value: Any) -> str | None:
    return None if value is None else json.dumps(value, ensure_ascii=False)


def jload(value: str | None, default: Any = None) -> Any:
    if not value:
        return default
    try:
        return json.loads(value)
    except (ValueError, TypeError):
        return default
